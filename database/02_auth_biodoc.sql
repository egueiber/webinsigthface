-- Complemento ao schema base (01_schema_base.sql).
--
-- Estas alteracoes ja tinham sido aplicadas manualmente no banco de producao
-- em algum momento (documentadas no CONTEXTO.md da migracao pra web), mas
-- nunca tinham sido incorporadas ao script versionado do projeto. Isso fazia
-- com que qualquer maquina NOVA (volume do Postgres vazio) subisse um banco
-- incompleto: sem tabela de usuarios, sem os campos da integracao Biodoc.
--
-- Idempotente: seguro rodar mais de uma vez (tudo com IF NOT EXISTS).
-- Roda automaticamente apos o 01_schema_base.sql (o Postgres executa os
-- arquivos de /docker-entrypoint-initdb.d/ em ordem alfabetica).
-- ============================================================================

-- Autenticacao (tela de login do sistema web).
CREATE TABLE IF NOT EXISTS sch_supervisorio.tb_usuario
(
    idusuario     bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nomeusuario   character varying(100) NOT NULL,
    login         character varying(50)  NOT NULL,
    senhahash     character varying(255) NOT NULL,
    papel         character varying(20)  NOT NULL DEFAULT 'user',
    ativo         boolean NOT NULL DEFAULT true,
    datacriacao   timestamp without time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_usuario_pkey PRIMARY KEY (idusuario),
    CONSTRAINT tb_usuario_login_unique UNIQUE (login),
    CONSTRAINT tb_usuario_papel_check CHECK (papel IN ('admin', 'user'))
);

-- Numero da carteirinha do beneficiario na Biodoc (cadastro de Pessoa).
ALTER TABLE sch_supervisorio.tb_pessoa
    ADD COLUMN IF NOT EXISTS "carteirinhaBiodoc" character varying(50);

-- URL e token da API da Biodoc (tela de Parametros).
ALTER TABLE sch_supervisorio.tb_parametro
    ADD COLUMN IF NOT EXISTS biodocapiurl character varying(600) COLLATE pg_catalog."default";
ALTER TABLE sch_supervisorio.tb_parametro
    ADD COLUMN IF NOT EXISTS biodocapitoken character varying(800) COLLATE pg_catalog."default";

-- Horario "ao vivo" da deteccao, usado pra escolher o frame mais proximo
-- na tela de Acompanhamento (ver /media/detection-frame no backend).
ALTER TABLE sch_supervisorio.tb_videos_processados
    ADD COLUMN IF NOT EXISTS datahora_ao_vivo timestamp without time zone;
